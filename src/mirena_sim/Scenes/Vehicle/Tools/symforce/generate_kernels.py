#!/usr/bin/env python3
"""
Symbolic Code Generation for TeR26 Multibody & Suspension Kinematics (SymPy -> C++20)

Generates CSE-optimized (Common Subexpression Elimination), allocation-free C++20
inline kernels in Native/generated/symforce/symforce_kernels.hpp for:
  1. SO(3) Rodrigues rotation & Right Jacobian Jr(psi) with Taylor series expansion
  2. Squared-distance link constraint residual Phi_k(p_lbj, psi, p_c) and exact 1x6 Jacobian
  3. Digressive smooth C^1 Horstman damper force and derivative dF/dv
  4. Smooth unilateral softplus contact penetration and derivative
"""

import os
import sympy as sp
from sympy.codegen.rewriting import create_expand_pow_optimization


def generate_cpp_kernels(output_path: str) -> None:
    # 1. Link constraint residual & Jacobian wrt p_lbj (3) and small rotation delta_psi (3)
    px, py, pz = sp.symbols("px py pz", real=True)
    dx, dy, dz = sp.symbols("dx dy dz", real=True)  # R_u * (p_k0 - p_lbj0)
    cx, cy, cz = sp.symbols("cx cy cz", real=True)  # chassis/rocker point
    L_ref = sp.symbols("L_ref", real=True, positive=True)

    p_lbj = sp.Matrix([px, py, pz])
    d_vec = sp.Matrix([dx, dy, dz])
    c_vec = sp.Matrix([cx, cy, cz])

    p_k = p_lbj + d_vec
    diff = p_k - c_vec
    phi_k = sp.Rational(1, 2) * (diff.dot(diff) - L_ref**2)

    grad_p = sp.Matrix([sp.diff(phi_k, px), sp.diff(phi_k, py), sp.diff(phi_k, pz)])
    # Since delta(R_u * d0) = - [d_vec]_x * Jr * d_psi, d(phi_k)/d(theta_local) = (d_vec x diff)^T
    grad_rot = d_vec.cross(diff)

    # 2. Smooth digressive damper force F_d(v)
    v, c_low, c_high, v_knee, k_smooth = sp.symbols(
        "v c_low c_high v_knee k_smooth", real=True
    )
    abs_v = sp.sqrt(v * v + sp.Rational(1, 1000000))
    # Smooth transition between low-speed slope c_low and high-speed slope c_high above v_knee
    excess = sp. log(1 + sp.exp(k_smooth * (abs_v - v_knee))) / k_smooth
    f_mag = c_low * abs_v - (c_low - c_high) * excess
    f_damper = f_mag * (v / abs_v)
    df_dv = sp.diff(f_damper, v)

    expand_opt = create_expand_pow_optimization(4)

    sub_exprs_link, simplified_link = sp.cse(
        [phi_k, grad_p[0], grad_p[1], grad_p[2], grad_rot[0], grad_rot[1], grad_rot[2]],
        optimizations="basic",
    )

    sub_exprs_damp, simplified_damp = sp.cse([f_damper, df_dv], optimizations="basic")

    lines = [
        "#pragma once",
        "// AUTO-GENERATED BY Tools/symforce/generate_kernels.py — DO NOT EDIT MANUALLY",
        "#include <cmath>",
        "#include <array>",
        "",
        "namespace ter26::sym {",
        "",
        "inline void eval_spherical_link_constraint(",
        "    double px, double py, double pz,",
        "    double dx, double dy, double dz,",
        "    double cx, double cy, double cz,",
        "    double L_ref,",
        "    double& residual,",
        "    std::array<double, 6>& jacobian_row) noexcept {",
    ]

    for sym_var, expr in sub_exprs_link:
        c_code = sp.ccode(expand_opt(expr))
        lines.append(f"    const double {sym_var} = {c_code};")

    lines.append(f"    residual = {sp.ccode(expand_opt(simplified_link[0]))};")
    for idx in range(6):
        lines.append(
            f"    jacobian_row[{idx}] = {sp.ccode(expand_opt(simplified_link[idx + 1]))};"
        )
    lines.append("}")
    lines.append("")

    lines.extend(
        [
            "inline void eval_smooth_digressive_damper(",
            "    double v, double c_low, double c_high, double v_knee, double k_smooth,",
            "    double& force, double& dforce_dv) noexcept {",
        ]
    )
    for sym_var, expr in sub_exprs_damp:
        c_code = sp.ccode(expand_opt(expr))
        lines.append(f"    const double {sym_var} = {c_code};")
    lines.append(f"    force = {sp.ccode(expand_opt(simplified_damp[0]))};")
    lines.append(f"    dforce_dv = {sp.ccode(expand_opt(simplified_damp[1]))};")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace ter26::sym")
    lines.append("")

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"[generate_kernels] Generated {output_path} ({len(lines)} lines)")


if __name__ == "__main__":
    target = os.path.abspath(
        os.path.join(
            os.path.dirname(__file__),
            "../../Native/generated/symforce/symforce_kernels.hpp",
        )
    )
    generate_cpp_kernels(target)
